test('teclado, selección visible y Escape contextual en detalle', async ({ page }) => {
  await page.goto('/proyectos?category=personal&slug=ayc&source=bookmark')
  await expect(page.locator('main h1')).toHaveAccessibleName('Argenis y Carolina')
  await page.locator('main').focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('main h1')).toHaveAccessibleName('OG Stickers')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/proyectos\/og-stickers\?/)
  await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page).toHaveURL(/\/proyectos\/og-stickers\?/)
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/proyectos\?/)
  await expect(page.locator('main h1')).toHaveAccessibleName('OG Stickers')
  expect(new URL(page.url()).searchParams.get('source')).toBe('bookmark')
})

